"""Unified data sources for experiments.

Every experiment (EKB / MACSA / benchmark) differs only in WHERE its data comes
from -- this module hides that behind a single ``DataSource.load() -> Instance``
contract so the experiment runner is identical across them. New experiments add
a data source, not a new notebook cell.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

import torch

from .helpers import as_route_tensor


@dataclass
class Instance:
    """A loaded problem instance: tensors + initial routes + route bounds."""

    label: str
    tensors: dict
    init_routes: torch.Tensor
    spec: dict                       # n_routes / min_route_len / max_route_len
    coords: Any = None               # node_locs, for route plotting
    street_adj: Any = None           # street adjacency, for route plotting
    meta: dict = field(default_factory=dict)


class DataSource:
    def load(self) -> Instance:
        raise NotImplementedError


class EKBDataSource(DataSource):
    """Ekaterinburg case study (loads tensors + seed routes from disk)."""

    def load(self) -> Instance:
        from .ekb import load_ekb_tensors, load_ekb_routes, ekb_spec
        tensors = load_ekb_tensors()
        routes = load_ekb_routes()
        init = as_route_tensor(routes)
        return Instance(
            label="EKB", tensors=tensors, init_routes=init, spec=ekb_spec(routes),
            coords=tensors["node_locs"], street_adj=tensors["street_adj"],
            meta={"crs": "gis"},
        )


class MACSADataSource(DataSource):
    """A MACSA scenario (tensors + seeded routes from a scenario dir)."""

    def __init__(self, scenario: str):
        self.scenario = scenario

    def load(self) -> Instance:
        from connectpt.routes_generator.citygraph_dataset import load_macsa_scenario
        from .context import MACSA_DATA_DIR
        from .paper import macsa_eval_bounds
        sc = load_macsa_scenario(MACSA_DATA_DIR / self.scenario)
        n_routes, min_len, max_len = macsa_eval_bounds(sc)
        tensors = sc["tensors"]
        return Instance(
            label=f"MACSA/{self.scenario}", tensors=tensors,
            init_routes=as_route_tensor(sc["routes"]),
            spec={"n_routes": n_routes, "min_route_len": min_len, "max_route_len": max_len},
            coords=tensors["node_locs"], street_adj=tensors["street_adj"],
        )


class BenchmarkDataSource(DataSource):
    """A standard benchmark city (Mandl / Mumford). Init routes are loaded from
    a saved route dump when given, else generated by LC + the realistic tier."""

    def __init__(self, city: str, init_routes_path: str | None = None, seed: int = 0):
        self.city = city
        self.init_routes_path = init_routes_path
        self.seed = seed

    def load(self) -> Instance:
        from .baselines import load_benchmark_tensors, BENCHMARK_SPECS
        tensors = load_benchmark_tensors(self.city)
        spec = next(s for s in BENCHMARK_SPECS if s["city"] == self.city)
        init = self._make_init(tensors, spec)
        return Instance(
            label=self.city, tensors=tensors, init_routes=init, spec=dict(spec),
            coords=tensors["node_locs"], street_adj=tensors["street_adj"],
        )

    def _make_init(self, tensors, spec):
        import torch as _torch
        if self.init_routes_path:
            from .helpers import load_routes_tensor
            return as_route_tensor(load_routes_tensor(self.init_routes_path))
        # LC construction + realistic-tier corruption (the E1 init pipeline)
        import random as _random
        from .helpers import build_lc_cfg, run_lc
        from .route_copies import inject_realistic_tier, pad_routes
        from connectpt.routes_generator.objectives import load_unified_objective
        _obj = load_unified_objective()
        cfg = build_lc_cfg(run_name=f"lc_init_{self.city}", n_routes=spec["n_routes"],
                           min_route_len=spec["min_route_len"],
                           max_route_len=spec["max_route_len"],
                           connectivity_mode=_obj.connectivity_mode, **_obj.weights)
        clean = run_lc(cfg, tensors=tensors, run_name_prefix=f"lc_init_{self.city}_",
                       n_samples=1)[3]
        clean = pad_routes(clean, spec["n_routes"], spec["max_route_len"])
        rng = _random.Random(self.seed)
        init, _ = inject_realistic_tier(
            clean, rng, spec["min_route_len"], spec["max_route_len"],
            street_adj=tensors["street_adj"], demand=tensors["demand"],
            n_nodes=tensors["node_locs"].shape[0])
        init = as_route_tensor(init)
        return init[None] if init.ndim == 2 else init


REGISTRY = {
    "ekb": EKBDataSource,
    "macsa": MACSADataSource,
    "benchmark": BenchmarkDataSource,
}


def create_data_source(data_cfg) -> DataSource:
    """Build a DataSource from a ``data:`` config node (``source`` + params)."""
    params = {k: v for k, v in dict(data_cfg).items() if k != "source"}
    return REGISTRY[data_cfg["source"]](**params)
